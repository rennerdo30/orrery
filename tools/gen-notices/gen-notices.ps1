# Regenerates THIRD_PARTY_NOTICES: the vendored JavaScript sections (header.txt) followed by one
# section per Rust crate linked into the Windows release exe (crate, version, licence, and the
# crate's own LICENSE / COPYING / NOTICE files from the local cargo registry).
# Needs only cargo (already installed) and a fetched registry (cargo fetch / a prior build).
# Usage: powershell -File tools\gen-notices\gen-notices.ps1
$ErrorActionPreference = 'Stop'
$root = (Resolve-Path (Join-Path $PSScriptRoot '..\..')).Path
Push-Location $root
try {
  $target = 'x86_64-pc-windows-msvc'
  $meta = cargo metadata --format-version 1 --locked --filter-platform $target | ConvertFrom-Json
  # normal (linked) dependencies only: no build scripts, no dev dependencies, no proc-macros
  $tree = cargo tree --locked -e normal --target $target --prefix none --format '{p}' | Sort-Object -Unique
  $linked = foreach ($l in $tree) {
    if ($l -match '\(proc-macro\)') { continue }
    if ($l -match '^(\S+) v(\S+)') { if ($Matches[1] -ne 'orrery') { [pscustomobject]@{ Name = $Matches[1]; Version = $Matches[2] } } }
  }
  $sb = New-Object System.Text.StringBuilder
  [void]$sb.Append((Get-Content (Join-Path $PSScriptRoot 'header.txt') -Raw))
  [void]$sb.AppendLine('')
  [void]$sb.AppendLine('================================================================')
  [void]$sb.AppendLine("Rust crates linked into orrery.exe ($target, $(@($linked).Count) crates)")
  [void]$sb.AppendLine('Generated by tools/gen-notices/gen-notices.ps1 from cargo metadata and the crates'' own files.')
  [void]$sb.AppendLine('================================================================')
  $noLicense = @()
  foreach ($c in ($linked | Sort-Object Name, Version)) {
    $p = $meta.packages | Where-Object { $_.name -eq $c.Name -and $_.version -eq $c.Version } | Select-Object -First 1
    if (-not $p) { throw "crate not in metadata: $($c.Name) $($c.Version)" }
    $dir = Split-Path $p.manifest_path
    $lic = if ($p.license) { $p.license } else { "(see license_file: $($p.license_file))" }
    [void]$sb.AppendLine('')
    [void]$sb.AppendLine("---- $($c.Name) $($c.Version) -- $lic")
    if ($p.repository) { [void]$sb.AppendLine("source: $($p.repository)") }
    $files = Get-ChildItem -LiteralPath $dir -File -ErrorAction SilentlyContinue |
      Where-Object { $_.Name -match '^(LICEN[SC]E|COPYING|NOTICE|UNLICENSE|COPYRIGHT)' -and $_.Name -notmatch '\.(rs|toml)$' } | Sort-Object Name
    if ($files) {
      foreach ($f in $files) {
        [void]$sb.AppendLine('')
        [void]$sb.AppendLine("[$($f.Name)]")
        [void]$sb.AppendLine((Get-Content -LiteralPath $f.FullName -Raw).TrimEnd())
      }
    } else {
      $noLicense += $c.Name
      $authors = if ($p.authors -and $p.authors.Count) { ($p.authors -join '; ') } else { '(none listed)' }
      [void]$sb.AppendLine('')
      [void]$sb.AppendLine("[no licence file shipped in this crate: licence taken from Cargo.toml]")
      [void]$sb.AppendLine("License (SPDX): $lic")
      [void]$sb.AppendLine("Authors (Cargo.toml): $authors")
    }
  }
  $out = Join-Path $root 'THIRD_PARTY_NOTICES'
  [IO.File]::WriteAllText($out, $sb.ToString().Replace("`r`n", "`n"), (New-Object Text.UTF8Encoding($false)))
  Write-Host "Wrote $out ($(@($linked).Count) crates; without licence file: $($noLicense -join ', '))"
} finally { Pop-Location }
